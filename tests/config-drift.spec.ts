import { test, expect } from '@playwright/test';
import * as dotenv from 'dotenv';
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { snQuery } from '../utils/servicenow-api';
import { diffFields, isKnownBenign, loadCapturedRecords, truncate, type CapturedRecord, type FieldDiff } from '../utils/drift';

/**
 * Config drift detection for the target instance (whatever E2E_ENV_FILE points at).
 *
 * Layer 1 — captured vs. target: every record in the golden-demo update sets
 *   (sales-crm-golden-demo/update-sets/UPDATE-*.xml) must exist on the target with the same
 *   field values. One test per update set, so a failure names the set that did not land.
 * Layer 2 — source vs. target: compares the instance the update sets were captured from
 *   (default: .env, i.e. opmsalescrm1) against the target for the same tables, to catch
 *   (a) records changed on the source after the capture and (b) records created on the source
 *   that no update set contains and that are missing on the target.
 *
 * Both layers are read-only. Findings are written to drift-reports/ (tracked) so they can be
 * turned into new update sets or post-deploy scripts.
 */

const UPDATE_SETS_DIR = resolve(process.env.UPDATE_SETS_DIR ?? '../sales-crm-golden-demo/update-sets');
const SOURCE_ENV_FILE = process.env.SOURCE_ENV_FILE ?? '.env';
// Demo build started after the 2026-08-22 plugin baseline (see opmsalescrm1 capture notes).
const SOURCE_SINCE = process.env.SOURCE_SINCE ?? '2026-08-23 00:00:00';
const BATCH_THRESHOLD = Number(process.env.DRIFT_BATCH_THRESHOLD ?? 8);
const PLUGIN_AUTHORS = ['system', 'maint', 'glide.maint', 'guest', 'snc.sa.core'];
// Tables whose rows are mostly generated by plugin installs / runtime activity, so "created on
// source, absent on target" is not a useful signal there.
const NOISY_TABLES = new Set([
  'sys_documentation',
  'sys_dictionary',
  'sys_db_object',
  'sys_variable_value',
  'sys_security_acl',
  'sys_security_acl_role',
  'sys_user_preference',
]);
// Config tables the update sets may not touch yet but a demo change could land in.
const EXTRA_TABLES = [
  'sys_script',
  'sys_script_include',
  'sys_ui_action',
  'sys_ui_policy',
  'sys_client_script',
  'sys_security_acl',
  'sys_hub_flow',
  'sys_user_role_contains',
  'sys_ux_screen',
  'sys_ux_macroponent',
  'sys_ui_section',
  'sys_ui_view',
];

const targetUrl = (process.env.SERVICENOW_INSTANCE_URL ?? '').replace(/\/$/, '');
const { records, skipped } = existsSync(UPDATE_SETS_DIR)
  ? loadCapturedRecords(UPDATE_SETS_DIR)
  : { records: [] as CapturedRecord[], skipped: [] as string[] };

interface Finding {
  layer: 1 | 2;
  kind: 'missing-on-target' | 'field-mismatch' | 'unreadable-table' | 'changed-after-capture' | 'uncaptured-missing-on-target';
  updateSet?: string;
  table: string;
  sysId?: string;
  label?: string;
  detail?: string;
  diffs?: FieldDiff[];
}
// Playwright restarts the worker after a failed test, which wipes module state — so findings are
// appended to a file (truncated once by global-setup.ts) and the report is built from the file.
const FINDINGS_FILE = resolve('results/drift-findings.jsonl');
const findings = {
  push(...items: Finding[]) {
    if (!items.length) return;
    mkdirSync(resolve('results'), { recursive: true });
    appendFileSync(FINDINGS_FILE, items.map((i) => JSON.stringify(i)).join('\n') + '\n');
  },
  all(): Finding[] {
    return existsSync(FINDINGS_FILE)
      ? readFileSync(FINDINGS_FILE, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l) as Finding)
      : [];
  },
};

function chunk<T>(a: T[], n: number): T[][] {
  const out: T[][] = [];
  for (let i = 0; i < a.length; i += n) out.push(a.slice(i, i + n));
  return out;
}

// ---- Source-instance REST helper (separate from the target helper in utils/servicenow-api.ts) ----
function sourceClient() {
  if (!existsSync(SOURCE_ENV_FILE)) return null;
  const env = dotenv.parse(readFileSync(SOURCE_ENV_FILE));
  const url = (env.SERVICENOW_INSTANCE_URL ?? '').replace(/\/$/, '');
  const user = env.SERVICENOW_API_USERNAME ?? env.SERVICENOW_USERNAME;
  const pass = env.SERVICENOW_API_PASSWORD ?? env.SERVICENOW_PASSWORD;
  if (!url || !user || !pass || url === targetUrl) return null;
  const auth = 'Basic ' + Buffer.from(`${user}:${pass}`).toString('base64');
  return {
    url,
    async query(table: string, query: string, fields: string): Promise<Record<string, any>[]> {
      const all: Record<string, any>[] = [];
      for (let offset = 0; ; offset += 500) {
        const params = new URLSearchParams({
          sysparm_query: query,
          sysparm_fields: fields,
          sysparm_display_value: 'false',
          sysparm_exclude_reference_link: 'true',
          sysparm_limit: '500',
          sysparm_offset: String(offset),
        });
        const res = await fetch(`${url}/api/now/table/${table}?${params}`, {
          headers: { Authorization: auth, Accept: 'application/json' },
        });
        if (!res.ok) throw new Error(`${res.status}`);
        const rows = ((await res.json()) as { result: Record<string, any>[] }).result;
        all.push(...rows);
        if (rows.length < 500) return all;
      }
    },
  };
}


test.describe('Layer 1 — update sets are applied on the target', () => {
  test('update-set XMLs are readable', () => {
    expect(existsSync(UPDATE_SETS_DIR), `UPDATE_SETS_DIR not found: ${UPDATE_SETS_DIR}`).toBe(true);
    expect(records.length).toBeGreaterThan(0);
    if (skipped.length) console.log(`Not checkable (no sys_id in payload): ${skipped.join('; ')}`);
  });

  const bySet = new Map<string, CapturedRecord[]>();
  for (const r of records) bySet.set(r.updateSet, [...(bySet.get(r.updateSet) ?? []), r]);

  for (const [updateSet, recs] of bySet) {
    test(updateSet, async () => {
      test.setTimeout(300_000);
      const local: Finding[] = [];
      const byTable = new Map<string, CapturedRecord[]>();
      for (const r of recs) byTable.set(r.table, [...(byTable.get(r.table) ?? []), r]);

      for (const [table, tableRecs] of byTable) {
        for (const group of chunk(tableRecs, 20)) {
          const fieldNames = new Set<string>(['sys_id']);
          for (const r of group) Object.keys(r.fields).forEach((f) => fieldNames.add(f));
          let rows: Record<string, any>[];
          try {
            rows = await snQuery(table, `sys_idIN${group.map((r) => r.sysId).join(',')}`, [...fieldNames].join(','), 'false');
          } catch (e) {
            local.push({ layer: 1, kind: 'unreadable-table', updateSet, table, detail: String(e).slice(0, 160) });
            break;
          }
          const found = new Map(rows.map((row) => [row.sys_id as string, row]));
          for (const r of group) {
            const row = found.get(r.sysId);
            if (!row && table === 'sys_dictionary' && r.fields.name && r.fields.element) {
              // OOB fields carry per-instance sys_ids; fall back to the natural key (table + element).
              const alt = await snQuery(table, `name=${r.fields.name}^element=${r.fields.element}`, [...fieldNames].join(','), 'false');
              if (alt[0]) {
                const diffs = diffFields(r.fields, alt[0]).filter((d) => !isKnownBenign(table, d));
                if (diffs.length) local.push({ layer: 1, kind: 'field-mismatch', updateSet, table, sysId: r.sysId, label: `${r.fields.name}.${r.fields.element}`, diffs });
                continue;
              }
            }
            if (!row) {
              local.push({ layer: 1, kind: 'missing-on-target', updateSet, table, sysId: r.sysId, label: r.fields.name ?? r.fields.short_description ?? r.label });
              continue;
            }
            const diffs = diffFields(r.fields, row).filter((d) => !isKnownBenign(table, d));
            if (diffs.length) {
              local.push({ layer: 1, kind: 'field-mismatch', updateSet, table, sysId: r.sysId, label: r.fields.name ?? r.fields.short_description ?? r.label, diffs });
            }
          }
        }
      }

      findings.push(...local);
      const real = local.filter((f) => f.kind !== 'unreadable-table');
      const summary = real
        .slice(0, 25)
        .map((f) => `${f.kind} ${f.table} ${f.sysId} (${f.label ?? ''})${f.diffs ? ' ' + f.diffs.map((d) => d.field).join(',') : ''}`)
        .join('\n');
      expect(real, `${real.length} drifted record(s) in ${updateSet} of ${recs.length}:\n${summary}`).toHaveLength(0);
    });
  }
});

test.describe('Layer 2 — source instance vs. target', () => {
  test('records changed or created on the source are present on the target', async () => {
    test.setTimeout(900_000);
    const src = sourceClient();
    test.skip(!src, `No usable source instance in ${SOURCE_ENV_FILE} (missing, or same as target)`);
    const source = src!;

    const captured = new Set(records.map((r) => r.sysId));
    const capturedAt = readdirCaptureTime();
    const tables = [...new Set([...records.map((r) => r.table), ...EXTRA_TABLES])].sort();
    const local: Finding[] = [];
    const uncaptured: (Finding & { created: string })[] = [];

    for (const table of tables) {
      let rows: Record<string, any>[];
      try {
        rows = await source.query(
          table,
          `sys_updated_on>=${SOURCE_SINCE}^sys_created_by!=${PLUGIN_AUTHORS.join('^sys_created_by!=')}^sys_created_byNOT LIKE@snc`,
          'sys_id,sys_created_by,sys_created_on,sys_updated_by,sys_updated_on,name,short_description'
        );
      } catch (e) {
        local.push({ layer: 2, kind: 'unreadable-table', table, detail: `source ${String(e)}` });
        continue;
      }
      if (!rows.length) continue;

      const onTarget = new Set<string>();
      for (const group of chunk(rows, 40)) {
        try {
          const t = await snQuery(table, `sys_idIN${group.map((r) => r.sys_id).join(',')}`, 'sys_id', 'false');
          t.forEach((r) => onTarget.add(r.sys_id));
        } catch {
          local.push({ layer: 2, kind: 'unreadable-table', table, detail: 'target' });
          break;
        }
      }

      for (const row of rows) {
        const label = row.name || row.short_description || '';
        const detail = `source created ${row.sys_created_on} by ${row.sys_created_by}; updated ${row.sys_updated_on} by ${row.sys_updated_by}`;
        if (captured.has(row.sys_id)) {
          if (row.sys_updated_on > capturedAt) {
            local.push({ layer: 2, kind: 'changed-after-capture', table, sysId: row.sys_id, label, detail });
          }
        } else if (row.sys_created_on >= SOURCE_SINCE && !NOISY_TABLES.has(table) && !onTarget.has(row.sys_id)) {
          uncaptured.push({ layer: 2, kind: 'uncaptured-missing-on-target', table, sysId: row.sys_id, label, detail, created: String(row.sys_created_on) } as Finding & { created: string });
        }
      }
    }

    // Plugin activation / app installs write hundreds of rows in the same minute. A minute that
    // produced 8+ uncaptured rows across tables is an install batch, not a hand-made demo change.
    const perMinute = new Map<string, number>();
    for (const u of uncaptured) perMinute.set(u.created.slice(0, 16), (perMinute.get(u.created.slice(0, 16)) ?? 0) + 1);
    for (const u of uncaptured) {
      if ((perMinute.get(u.created.slice(0, 16)) ?? 0) < BATCH_THRESHOLD) {
        const { created: _c, ...f } = u;
        local.push(f);
      }
    }

    findings.push(...local);
    const real = local.filter((f) => f.kind !== 'unreadable-table');
    const summary = real
      .slice(0, 25)
      .map((f) => `${f.kind} ${f.table} ${f.sysId} (${truncate(f.label ?? '', 50)})`)
      .join('\n');
    expect(real, `${real.length} source change(s) not reflected on target:\n${summary}`).toHaveLength(0);
  });
});

function readdirCaptureTime(): string {
  // Latest <unload_date> across the update-set files = when the newest capture was cut.
  let latest = '';
  for (const r of new Set(records.map((x) => x.updateSet))) {
    const head = readFileSync(resolve(UPDATE_SETS_DIR, r), 'utf8').slice(0, 300);
    const d = head.match(/unload_date="([^"]+)"/)?.[1] ?? '';
    if (d > latest) latest = d;
  }
  return latest;
}
